"""Generate the frontend contract from the canonical Pydantic schema; no hand-maintained shape drift."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.schemas.modules import CanonicalResearchResult
schema = CanonicalResearchResult.model_json_schema()
def ts(node):
    if '$ref' in node: return node['$ref'].split('/')[-1]
    if 'enum' in node: return ' | '.join(repr(v) for v in node['enum'])
    if 'const' in node: return repr(node['const'])
    if 'anyOf' in node: return ' | '.join(ts(n) for n in node['anyOf'])
    kind=node.get('type')
    if kind == 'array': return 'Array<' + ts(node['items']) + '>'
    if kind == 'object':
        if 'properties' not in node: return 'Record<string, ' + ts(node.get('additionalProperties', {})) + '>'
        required=node.get('required', [])
        return '{\n' + '\n'.join(f"  {k}{'' if k in required else '?'}: {ts(v)};" for k,v in node['properties'].items()) + '\n}'
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')
text='// Generated by backend/scripts/generate_result_contract.py\n'
for name, item in schema.get('$defs', {}).items(): text += f'export type {name} = {ts(item)};\n'
text += f'export type CanonicalResearchResult = {ts(schema)};\n'
Path(__file__).resolve().parents[2].joinpath('frontend/src/services/result-contract.d.ts').write_text(text)
